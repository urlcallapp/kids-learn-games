export function checkAnswer(question,value){
 if(question.kind==='multi')return Array.isArray(value)&&value.length===question.answer.length&&question.answer.every(x=>value.includes(x));
 if(question.kind==='pair'){if(!Array.isArray(value)||value.length!==2)return false;const a=value.map(numberValue);return a.every((n,i)=>n===question.answer[i]);}
 if(typeof question.answer==='number')return numberValue(value)===question.answer;
 return value===question.answer;
}
